// Reads the Tailwind-compiled CSS from dist/styles.css and emits a TS module
// that injects it into document.head once on import. Importing this module
// from src/index.ts means consumers get styles automatically — no need for
// `import '@bytive/jewel-try-me/styles.css'`.
import { readFileSync, writeFileSync } from 'node:fs';

const cssPath = 'dist/styles.css';
const outPath = 'src/styles.generated.ts';

const css = readFileSync(cssPath, 'utf8');
const escaped = css
  .replace(/\\/g, '\\\\')
  .replace(/`/g, '\\`')
  .replace(/\$\{/g, '\\${');

const content = `// AUTO-GENERATED from dist/styles.css. Do not edit by hand.
// Regenerated by scripts/build-style-injector.mjs during \`bun run build\`.
const css = \`${escaped}\`;
const ID = 'bytive-tryon-styles';
if (typeof document !== 'undefined' && !document.getElementById(ID)) {
  const style = document.createElement('style');
  style.id = ID;
  style.textContent = css;
  document.head.appendChild(style);
}
export {};
`;

writeFileSync(outPath, content, 'utf8');
console.log(`Generated ${outPath} (${css.length} chars of CSS embedded)`);
